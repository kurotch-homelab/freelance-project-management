import { once } from "node:events";
import { createServer, type Server } from "node:http";
import { getRequestListener } from "@hono/node-server";
import type { Config } from "./config.ts";
import { securityHeaders } from "./headers.ts";
import { startScheduler } from "./scheduler.ts";
import { buildServer, type ServerDeps } from "./server.ts";

function closeHttp(server: Server): Promise<void> {
  return new Promise((resolve, reject) => {
    server.close((error) => error ? reject(error) : resolve());
  });
}

export async function startServer(config: Config, deps: ServerDeps = {}) {
  const logger = deps.logger ?? console;
  const built = await buildServer(config, deps);
  const inFlight = new Set<Promise<void>>();
  let server: Server | undefined;
  try {
    const listener = getRequestListener(built.app.fetch, {
      overrideGlobalObjects: false,
      errorHandler: () => {
        logger.error("HTTP adapter failed");
        return new Response("Internal Server Error", {
          status: 500, headers: { ...securityHeaders, "Cache-Control": "no-store" },
        });
      },
    });
    server = createServer(async (incoming, outgoing) => {
      // Also cover responses generated by the HTTP adapter before Hono runs.
      for (const [name, value] of Object.entries(securityHeaders)) outgoing.setHeader(name, value);
      const pending = listener(incoming, outgoing);
      inFlight.add(pending);
      try {
        await pending;
      } catch {
        logger.error("HTTP adapter failed");
        outgoing.destroy();
      } finally {
        // A socket close is not completion: the handler may still be using the DB.
        inFlight.delete(pending);
      }
    });
    server.listen(config.port);
    await once(server, "listening");
  } catch (error) {
    if (server?.listening) await closeHttp(server);
    await built.close();
    throw error;
  }
  const httpServer = server;

  const stopScheduler = startScheduler({
    intervalMinutes: config.syncIntervalMinutes,
    run: built.sync,
    onError: () => logger.error("Scheduled sync failed"),
  });
  let stopping: Promise<void> | undefined;
  const stop = (): Promise<void> => {
    if (stopping) return stopping;
    const drained = stopScheduler();
    stopping = (async () => {
      try {
        // Stop accepting HTTP, then drain handlers (even disconnected ones) and syncs.
        const results = await Promise.allSettled([closeHttp(httpServer), drained]);
        while (inFlight.size > 0) await Promise.allSettled([...inFlight]);
        await built.close();
        if (results.some((result) => result.status === "rejected")) throw new Error("Shutdown failed");
      } finally {
        process.off("SIGTERM", onSignal);
        process.off("SIGINT", onSignal);
      }
    })();
    return stopping;
  };
  const onSignal = () => {
    void stop().catch(() => {
      logger.error("Shutdown failed");
      process.exitCode = 1;
    });
  };
  process.on("SIGTERM", onSignal);
  process.on("SIGINT", onSignal);
  server.on("error", () => {
    logger.error("HTTP server failed");
    process.exitCode = 1;
    onSignal();
  });
  logger.info("Server listening");
  return { app: built.app, server, stop };
}
